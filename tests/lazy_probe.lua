local h = dofile(vim.env.CP_CACHE_PLUGIN .. "/tests/helpers.lua")
h.finish(function()
  assert(not package.loaded.competitest)
  vim.cmd("CompetiTest receive status")
  assert(vim.g.cp_dispatch_calls == 1, "first lazy command bypassed dispatcher: " .. vim.inspect(vim.g.cp_dispatch_calls))
  local a = require("cp_cache.adapter")
  a.setup_dependency({})
  a.install_dispatch(function() vim.g.cp_dispatch_calls = vim.g.cp_dispatch_calls + 1; return true end)
  vim.cmd("CompetiTest run | let g:cp_bar = 1")
  assert(vim.g.cp_dispatch_calls == 2 and vim.g.cp_bar == 1)
  assert(vim.tbl_contains(vim.fn.getcompletion("CompetiTest receive st", "cmdline"), "stop"))
  print("P0 PASS: actual lazy first command, repeated setup, completion and -bar")
end)
