return function(h)
  local cp, a = require("cp_cache"), require("cp_cache.adapter")
  local root = h.root .. "/store/workflow-" .. vim.uv.hrtime()
  assert(cp.setup({ cache_root = root, picker = "select" }))
  local s = assert(cp.store())
  local messages, oldnotify, oldselect = {}, vim.notify, vim.ui.select
  vim.notify = function(message) messages[#messages + 1] = message end
  vim.ui.select = function(items, _, callback) callback(items[1]) end
  local buf, path = h.source("workflow/空 格 'quote'/main.cpp")
  local directory = vim.fs.dirname(path)
  local before = h.snapshot(directory)
  assert(next(cp.get_testcases(buf)) == nil)
  cp.add(buf)
  vim.api.nvim_buf_set_lines(vim.fn.bufnr("CompetiTestEditInput"), 0, -1, false, {"5", "1 2 3 4 5", ""})
  vim.api.nvim_buf_set_lines(vim.fn.bufnr("CompetiTestEditOutput"), 0, -1, false, {"15", ""})
  h.map(vim.fn.bufnr("CompetiTestEditInput"), "<C-s>")
  local p = assert(s:for_source(path)); assert(p.tests[1].id == 0 and p.tests[1].input == "5\n1 2 3 4 5\n")
  cp.edit(buf, 0); h.map(vim.fn.bufnr("CompetiTestEditInput"), "q")
  assert(s:for_source(path).revision == p.revision)
  cp.edit(buf, 0)
  p.name = "concurrent change"; assert(s:save(p, p.revision))
  vim.ui.select = function(items, _, callback) callback(items[#items]) end
  h.map(vim.fn.bufnr("CompetiTestEditInput"), "<C-s>")
  assert(s:for_source(path).revision == p.revision + 1)
  assert(table.concat(messages, "\n"):find("revision 冲突"))
  vim.ui.select = function(items, _, callback) callback(items[1]) end
  local shared, sharedpath = h.source("workflow/shared/B.cpp")
  assert(s:bind(sharedpath, p.id)); assert(cp.get_testcases(shared)[0])
  cp.edit(shared, 0)
  vim.api.nvim_buf_set_lines(vim.fn.bufnr("CompetiTestEditInput"), 0, -1, false, {"5", "1 2 3 4 5", ""})
  h.map(vim.fn.bufnr("CompetiTestEditInput"), "<C-s>")
  assert(cp.get_testcases(buf)[0].input == "5\n1 2 3 4 5\n")
  local files = assert(cp.export(buf, "files"))
  assert(h.read(files .. "/" .. p.id .. ".0.in") == "5\n1 2 3 4 5\n")
  local packed = assert(cp.export(buf, "msgpack"))
  assert(vim.mpack.decode(h.read(packed))[0].output == "15\n")
  vim.api.nvim_set_current_buf(buf)
  local runner = assert(cp.run(buf)); h.done(runner)
  for _, tc in pairs(runner.tcdata) do assert(tc.tcnum == "Compile" and tc.exit_code == 0 or tc.status == "CORRECT", tc.status) end
  local revised = assert(s:for_source(path)); revised.tests[1].output = "999\n"; assert(s:save(revised, revised.revision))
  local caseindex
  for i, tc in ipairs(runner.tcdata) do if tc.tcnum == 0 then caseindex = i end end
  vim.api.nvim_set_current_win(runner.ui.windows.tc.winid)
  vim.api.nvim_win_set_cursor(0, {caseindex, 0})
  h.map(runner.ui.windows.tc.bufnr, "R"); vim.wait(30); h.done(runner)
  assert(runner.tcdata[caseindex].status == "WRONG", "UI rerun used stale expected output")
  h.map(runner.ui.windows.tc.bufnr, "d")
  h.map(runner.ui.windows.tc.bufnr, "i"); assert(runner.ui.viewer_visible)
  runner.ui:hide_ui(); assert(cp.run(buf, {only_show=true}) == runner)
  a.resize(); vim.wait(50)
  revised = assert(s:for_source(path)); revised.tests[1].output = "15\n"; assert(s:save(revised, revised.revision))
  vim.api.nvim_set_current_win(runner.ui.windows.tc.winid)
  h.map(runner.ui.windows.tc.bufnr, "<C-r>"); vim.wait(50)
  runner = assert(a.runners()[buf]); h.done(runner)
  assert(runner.tcdata[2].status == "CORRECT")
  a.cleanup(buf)
  local mode = vim.system({"python", vim.fn.stdpath("config") .. "/scripts/cp_tool.py", "mode", path, "sanitize"}):wait(5000)
  assert(mode.code == 0)
  runner = assert(cp.run(buf)); h.done(runner)
  assert(runner.tcdata[1].exit_code == 0 and runner.tcdata[2].status == "CORRECT", vim.inspect(runner.tcdata))
  a.cleanup(buf)
  vim.api.nvim_set_current_buf(buf)
  assert(cp.setup({cache_root=root}))
  vim.cmd("CompetiTest run_no_compile 0"); runner = assert(a.runners()[buf]); h.done(runner)
  assert(#runner.tcdata == 1 and runner.tcdata[1].tcnum == 0)
  a.cleanup(buf)
  cp.delete(buf, 0); assert(next(cp.get_testcases(buf)) == nil and s:binding(path))
  assert(not cp.migrate(buf))
  cp.add(buf); h.map(vim.fn.bufnr("CompetiTestEditInput"), "<C-s>")
  assert(cp.get_testcases(buf)[0].output == "")
  cp.edit(buf, 0)
  vim.ui.select = function(items, _, callback) callback(items[2]) end
  h.map(vim.fn.bufnr("CompetiTestEditInput"), "<C-s>")
  assert(cp.get_testcases(buf)[0].output == nil)
  cp.edit(buf, 0)
  vim.api.nvim_set_current_win(vim.fn.bufwinid(buf))
  vim.api.nvim_buf_delete(buf, {force=true})
  vim.wait(50)
  assert(vim.fn.bufwinid("CompetiTestEditInput") == -1, vim.inspect({messages=messages,loaded=vim.api.nvim_buf_is_loaded(buf),wins=vim.api.nvim_list_wins(),errors=vim.v.errmsg}))
  assert(vim.deep_equal(before, h.snapshot(directory)), "workflow polluted source directory")
  vim.ui.select = function(items, _, callback) callback(items[1]) end
  local migbuf, migpath = h.source("workflow/migration/old.cpp")
  local olddir = vim.fs.dirname(migpath) .. "/testcases"
  h.write(olddir .. "/old.0.in", "中文\r\n\n"); h.write(olddir .. "/old.0.out", "")
  h.write(olddir .. "/old.2.in", "")
  local oldbefore = h.snapshot(vim.fs.dirname(migpath))
  assert(cp.migrate(migbuf)); assert(not cp.migrate(migbuf))
  assert(cp.get_testcases(migbuf)[0].input == "中文\r\n\n" and cp.get_testcases(migbuf)[0].output == "")
  assert(cp.get_testcases(migbuf)[2].output == nil)
  assert(vim.deep_equal(oldbefore, h.snapshot(vim.fs.dirname(migpath))))
  local mbuf, mpath = h.source("workflow/mpack/old.cpp")
  local name = assert(a.eval_file(mpath, a.config(mbuf).testcases_single_file_format))
  h.write(vim.fs.dirname(mpath) .. "/testcases/" .. name, vim.mpack.encode({[0]={input="",output=""},[3]={input="raw\r\n"}}))
  assert(cp.migrate(mbuf)); assert(cp.get_testcases(mbuf)[3].input == "raw\r\n")
  local pickbuf, pickpath = h.source("workflow/pick/renamed.cpp")
  local picked
  vim.ui.select = function(items, _, callback) picked = items[1]; callback(items[1]) end
  cp.pick(pickbuf); assert(s:for_source(pickpath).id == picked.id)
  vim.notify, vim.ui.select = oldnotify, oldselect
  print("P2 PASS: real editor/runner/rerun/diff/viewer/resize, sanitize, shared edits, empty/missing output, migration/export, fallback picker, directory snapshots")
end
