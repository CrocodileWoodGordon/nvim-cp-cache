local h = dofile(vim.env.CP_CACHE_PLUGIN .. "/tests/helpers.lua")
local a = require("cp_cache.adapter")
vim.schedule(function()
  h.finish(function()
    local buf = h.source("resize/" .. vim.uv.hrtime() .. "/main.cpp")
    local r = a.new_runner(buf)
    r:run_testcases({[0]={input="1\n2\n",output="2\n"}},true)
    r:show_ui(); h.done(r)
    h.write(vim.env.CP_CACHE_RESIZE_READY,"runner")
    h.await(function() return vim.o.columns==110 and vim.o.lines==38 end,"terminal runner resize not received")
    vim.wait(100)
    assert(r.ui.ui_visible and vim.api.nvim_win_is_valid(r.ui.windows.tc.winid))
    local config=vim.api.nvim_win_get_config(r.ui.windows.tc.winid)
    assert(config.width > 0 and config.width <= 110)
    r.ui:hide_ui()
    local saved
    a.editor_widget(buf,0,"keep\n", "2\n",function(tc) saved=tc end)
    vim.api.nvim_buf_set_lines(vim.fn.bufnr("CompetiTestEditInput"),0,-1,false,{"retained",""})
    h.write(vim.env.CP_CACHE_RESIZE_READY,"editor")
    h.await(function() return vim.o.columns==100 and vim.o.lines==34 end,"terminal editor resize not received")
    vim.wait(100)
    local input=vim.fn.bufnr("CompetiTestEditInput")
    assert(table.concat(vim.api.nvim_buf_get_lines(input,0,-1,false),"\n")=="retained\n")
    h.map(input,"<C-s>"); assert(saved.input=="retained\n" and saved.output=="2\n")
    a.cleanup(buf)
    h.write(vim.env.CP_CACHE_RESIZE_RESULT,vim.json.encode({status="PASS",runner={110,38},editor={100,34}}))
  end)
end)
